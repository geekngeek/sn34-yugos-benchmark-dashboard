"""Check how every source's model names were matched to model IDs, benchmark by benchmark.

    .venv/bin/python -I scripts/check_model_matches.py [--old-db llm_bench_old]

Writes docs/model-id-match-report.md and prints a summary. With --old-db (a database restored from the
backup taken before the model-ID change) it also compares every result's old and new identity.

Checks
  1. completeness   every result has a model ID and a raw name that is in data/models/aliases.csv;
                    with --old-db, every old result is still there (same source, benchmark, external_id)
  2. round trip     re-resolving each stored raw name gives the stored model ID, mode and snapshot
  3. over-merges    on one benchmark of one source, two DIFFERENT raw names resolve to the same
                    model + effort + mode + snapshot + date: either a duplicate listing or a wrong merge
  4. old vs new     models merged / split / effort changed compared with the old canonical keys
  5. review         models with results whose names differ only by packaging, vendor words or spacing
  6. Yugos          how each Yugos model is linked
"""
from __future__ import annotations

import argparse
import collections
import csv
import os
import sys
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from api.config import load_dotenv  # noqa: E402
from importer.normalize import split_effort  # noqa: E402
from importer.resolve import Resolver  # noqa: E402

REPORT = ROOT / "docs" / "model-id-match-report.md"

ROWS_SQL = """
SELECT s.source_name AS source, b.benchmark_name || COALESCE(' ' || b.benchmark_version, '') AS benchmark,
       r.external_id, m.canonical_key AS model_key, m.model_name, m.provider, r.raw_model_name AS raw,
       r.reasoning_effort AS effort, r.mode, r.model_snapshot AS snapshot, r.model_match AS match,
       r.evaluation_date::text AS date, r.benchmark_score::float AS score
FROM benchmark_results r JOIN sources s ON s.id = r.source_id
JOIN benchmarks b ON b.id = r.benchmark_id JOIN models m ON m.id = r.model_id
"""
OLD_SQL = """
SELECT s.source_name AS source, b.benchmark_name || COALESCE(' ' || b.benchmark_version, '') AS benchmark,
       r.external_id, m.canonical_key AS old_key, m.model_name AS old_name, r.reasoning_effort AS old_effort
FROM benchmark_results r JOIN sources s ON s.id = r.source_id
JOIN benchmarks b ON b.id = r.benchmark_id JOIN models m ON m.id = r.model_id
"""


def md_table(head: list[str], rows: list[list]) -> str:
    esc = lambda v: str(v if v is not None else "").replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--old-db", help="database restored from the pre-change backup, e.g. llm_bench_old")
    args = ap.parse_args()
    load_dotenv(ROOT / ".env")
    dsn = os.environ.get("DATABASE_URL", "postgresql://bench:bench@localhost:5432/llm_bench")
    with psycopg.connect(dsn, row_factory=dict_row) as conn:
        rows = conn.execute(ROWS_SQL).fetchall()
        priced = conn.execute("SELECT count(*) AS n FROM models m WHERE NOT EXISTS "
                              "(SELECT 1 FROM benchmark_results r WHERE r.model_id = m.id)").fetchone()["n"]
    old = None
    if args.old_db:
        old_dsn = dsn.rsplit("/", 1)[0] + "/" + args.old_db
        with psycopg.connect(old_dsn, row_factory=dict_row) as conn:
            old = {(r["source"], r["benchmark"], r["external_id"]): r for r in conn.execute(OLD_SQL).fetchall()}

    resolver = Resolver()
    aliases = {(r["source"], r["raw_name"]): r for r in
               csv.DictReader((ROOT / "data/models/aliases.csv").open(newline="", encoding="utf-8"))}
    sources = sorted({r["source"] for r in rows})
    problems: dict[str, list[str]] = collections.defaultdict(list)
    out: list[str] = ["# Model ID match report", "",
                      "Generated by `scripts/check_model_matches.py`. Every result's model name, as each source wrote it, "
                      "is resolved through `data/models/aliases.csv` (rules in `importer/model_ids.py`, decisions in "
                      "`data/models/overrides.csv`).", ""]

    # ---- 1 + 2. completeness and round trip ---------------------------------------------------------
    missing_alias, roundtrip, no_key = [], [], []
    for r in rows:
        if not r["model_key"]:
            no_key.append(r)
        if (r["source"], r["raw"]) not in aliases:
            missing_alias.append(r)
        res = resolver.resolve(r["source"], r["raw"], r["provider"])
        structured = r["effort"] is not None and r["effort"] != (res.effort) and r["effort"] != split_effort(r["raw"])[1]
        if (res.model_id, res.mode, res.snapshot) != (r["model_key"], r["mode"], r["snapshot"]) or \
                (not structured and (res.effort or None) != r["effort"]):
            roundtrip.append((r, res))
    old_missing = new_extra = 0
    if old is not None:
        new_keys = {(r["source"], r["benchmark"], r["external_id"]) for r in rows}
        old_missing = len(set(old) - new_keys)
        new_extra = len(new_keys - set(old))

    # ---- 3. over-merges: different raw names -> one configuration on one benchmark ----------------------
    cfg = collections.defaultdict(list)
    for r in rows:
        cfg[(r["source"], r["benchmark"], r["model_key"], r["effort"], r["mode"], r["snapshot"], r["date"])].append(r)
    over_same, over_diff, multi_runs = [], [], []
    for k, rs in cfg.items():
        names = collections.Counter(r["raw"] for r in rs)
        if len(names) < 2:
            continue
        if max(names.values()) > 1:          # the source already lists several runs under ONE name (agents, scaffolds)
            multi_runs.append((k, rs))
        else:
            (over_same if len({r["score"] for r in rs}) == 1 else over_diff).append((k, rs))

    # ---- 4. old vs new ------------------------------------------------------------------------------------
    merged, split, effort_changed = collections.defaultdict(set), collections.defaultdict(set), collections.Counter()
    if old is not None:
        for r in rows:
            o = old.get((r["source"], r["benchmark"], r["external_id"]))
            if not o:
                continue
            merged[r["model_key"]].add(o["old_key"])
            split[o["old_key"]].add(r["model_key"])
            if (o["old_effort"] or None) != (r["effort"] or None):
                effort_changed[(r["source"], r["raw"], o["old_effort"], r["effort"])] += 1
    merged = {k: v for k, v in merged.items() if len(v) > 1}
    split = {k: v for k, v in split.items() if len(v) > 1}

    # ---- per source summary --------------------------------------------------------------------------------
    by_src = collections.defaultdict(list)
    for r in rows:
        by_src[r["source"]].append(r)
    summary = []
    for s in sources:
        rs = by_src[s]
        m = collections.Counter(r["match"] for r in rs)
        n_over = sum(1 for k, _ in over_diff if k[0] == s)
        n_same = sum(1 for k, _ in over_same if k[0] == s)
        n_rt = sum(1 for r, _ in roundtrip if r["source"] == s)
        n_miss = sum(1 for r in missing_alias if r["source"] == s)
        old_models = len({old[(r["source"], r["benchmark"], r["external_id"])]["old_key"] for r in rs
                          if old and (r["source"], r["benchmark"], r["external_id"]) in old}) if old else ""
        summary.append([s, len(rs), len({r["raw"] for r in rs}), old_models, len({r["model_key"] for r in rs}),
                        m["yugos-exact"] + m["yugos-loose"] + m["yugos-same-model"], m["override"], m["rule"],
                        n_miss, n_rt, n_same, n_over])
        if n_miss: problems[s].append(f"{n_miss} results whose raw name is not in aliases.csv")
        if n_rt: problems[s].append(f"{n_rt} results that do not resolve the same way again")
        if n_over: problems[s].append(f"{n_over} different-score merges to review")
    out += ["## 1. Summary per source", "",
            md_table(["source", "results", "raw names", "models before", "models now", "via Yugos name", "override",
                      "rule only", "not in alias table", "round-trip mismatch", "dup listings (same score)",
                      "merges with different scores"], summary), "",
            f"- Results without a model ID: **{len(no_key)}**. Models with prices but no results: {priced}.",
            f"- Compared with the old database: {'not run' if old is None else f'**{old_missing}** old results missing, **{new_extra}** new ones (should both be 0)'}.",
            ""]

    # ---- 3. details ------------------------------------------------------------------------------------------
    def merge_rows(items):
        rows_ = []
        for (src, bench, key, eff, mode, snap, date), rs in sorted(items, key=lambda x: (x[0][0], x[0][1], x[0][2])):
            rows_.append([src, bench, key, f"{eff or ''}{'+' + mode if mode else ''}{' @' + snap if snap else ''}",
                          date or "", " ; ".join(f"{r['raw']} = {r['score']:g}" for r in sorted(rs, key=lambda r: r['raw']))])
        return rows_
    out += ["## 2. Different names merged into one configuration on one benchmark", "",
            "Same source, same benchmark, same date: two or more *different* model names resolved to the same model, "
            "effort, mode and snapshot. **Different scores** means the names may be different models (or runs) and "
            "need a decision; the same score is a duplicate listing by the source.", "",
            f"### 2a. Different scores ({len(over_diff)})", "",
            md_table(["source", "benchmark", "model ID", "config", "date", "names = scores"], merge_rows(over_diff)) if over_diff else "None.",
            "", f"### 2b. Several runs per model (agents or scaffolds), not a naming question ({len(multi_runs)})", "",
            "The source itself lists more than one result under one of these names on this benchmark "
            "(e.g. SWE-bench submissions by different agents using the same model).", "",
            md_table(["source", "benchmark", "model ID", "config", "date", "names = scores"], merge_rows(multi_runs)) if multi_runs else "None.",
            "", f"### 2c. Same score: duplicate listings ({len(over_same)})", "",
            md_table(["source", "benchmark", "model ID", "config", "date", "names = scores"], merge_rows(over_same)[:150]) if over_same else "None.",
            ""]

    # ---- 4. old vs new -----------------------------------------------------------------------------------------
    if old is not None:
        out += ["## 3. Compared with the old matching", "",
                f"### 3a. Merged: one model now, several before ({len(merged)})", "",
                md_table(["model ID now", "old keys"], [[k, " ; ".join(sorted(v))] for k, v in sorted(merged.items())]), "",
                f"### 3b. Split: one model before, several now ({len(split)})", "",
                md_table(["old key", "model IDs now"], [[k, " ; ".join(sorted(v))] for k, v in sorted(split.items())]), "",
                f"### 3c. Effort changed ({len(effort_changed)} names)", "",
                md_table(["source", "raw name", "effort before", "effort now", "results"],
                         [[s, raw, a or "—", b or "—", n] for (s, raw, a, b), n in sorted(effort_changed.items())]), ""]

    # ---- 5. review: possible splits --------------------------------------------------------------------------
    reg = list(csv.DictReader((ROOT / "data/models/registry.csv").open(newline="", encoding="utf-8")))
    with_results = {r["model_key"] for r in rows}
    loose = collections.defaultdict(list)
    for r in reg:
        if r["model_id"] in with_results:
            loose[r["loose_key"]].append(r)
    pairs = [v for v in loose.values() if len(v) > 1]
    out += ["## 4. Review: models whose names differ only by packaging or vendor words", "",
            "Kept apart on purpose (base vs instruct/chat/IT can be different weights). Join them with an "
            "`overrides.csv` row only when a source clearly means the same model.", "",
            md_table(["models", "names", "sources"],
                     [[" ; ".join(x["model_id"] for x in v), " ; ".join(x["raw_names"][:60] for x in v),
                       " ; ".join(x["sources"] for x in v)] for v in pairs]), ""]

    # ---- 6. Yugos --------------------------------------------------------------------------------------------
    yl = list(csv.DictReader((ROOT / "data/models/yugos-links.csv").open(newline="", encoding="utf-8")))
    c = collections.Counter(y["link"] for y in yl)
    out += ["## 5. Yugos models", "",
            ", ".join(f"{k}: **{v}**" for k, v in sorted(c.items())) + f" (of {len(yl)}); "
            f"with benchmark results: **{sum(1 for y in yl if y['model_id'] in with_results)}**.", "",
            "### Linked other than by exact name", "",
            md_table(["Yugos model", "link", "model ID", "note"],
                     [[y["yugos_model"], y["link"], y["model_id"], y["note"]] for y in yl if y["link"] not in ("exact", "none")]), "",
            "### Not linked to any benchmark model", "",
            ", ".join(f"`{y['yugos_model']}`" for y in yl if y["link"] == "none"), ""]

    unknown = sorted({r["model_key"] for r in rows if r["model_key"].startswith("unknown/")})
    out += ["## 6. Models with an unknown vendor", "", ", ".join(f"`{k}`" for k in unknown) or "None.", ""]

    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(out), encoding="utf-8")

    # ---- console summary ---------------------------------------------------------------------------------------
    print(f"{'source':38} {'results':>7} {'raw':>5} {'old':>5} {'new':>5} {'yugos':>6} {'ovr':>4} {'rule':>5} "
          f"{'!alias':>6} {'!rt':>4} {'dup':>4} {'MERGE?':>6}")
    for s in summary:
        print(f"{s[0][:38]:38} {s[1]:>7} {s[2]:>5} {s[3]:>5} {s[4]:>5} {s[5]:>6} {s[6]:>4} {s[7]:>5} {s[8]:>6} {s[9]:>4} {s[10]:>4} {s[11]:>6}")
    print(f"\nresults without model ID: {len(no_key)}; old results missing: {old_missing}; new results not in old: {new_extra}")
    print(f"not in alias table: {len(missing_alias)}; round-trip mismatches: {len(roundtrip)}")
    print(f"different-name merges on one benchmark: {len(over_diff)} with different scores, {len(over_same)} duplicate listings, "
          f"{len(multi_runs)} several-runs-per-model cases")
    if old is not None:
        print(f"vs old: {len(merged)} merged, {len(split)} split, {len(effort_changed)} names changed effort")
    print(f"unknown vendor models: {len(unknown)}")
    for r, res in roundtrip[:5]:
        print("  round-trip:", r["source"], r["raw"], (r["model_key"], r["effort"], r["mode"], r["snapshot"]), "->",
              (res.model_id, res.effort, res.mode, res.snapshot))
    print(f"report: {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
